import type { Fluid, Tokens } from "../../src/styles/tokens/tokens";

type Entry = [name: string, value: string];

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const px = (n: number) => (n === 0 ? "0" : `${n}px`);
const isFluid = (v: unknown): v is Fluid => typeof v === "object" && v !== null && "vw" in v;
const clamp = ({ min, vw, max }: Fluid) => `clamp(${min}px, ${vw}vw, ${max}px)`;
const size = (v: number | Fluid) => (isFluid(v) ? clamp(v) : px(v));

/** CSS custom property name for a space step: 2.5 → `--space-2_5`. */
export const spaceVar = (step: number) => `--space-${String(step).replace(".", "_")}`;

/** Every token as a CSS custom property, in a stable order. */
export function cssVariables(t: Tokens): Entry[] {
  const out: Entry[] = [];
  const add = (prefix: string, rec: Record<string, string | number>, fmt: (v: never) => string) => {
    for (const [k, v] of Object.entries(rec)) out.push([`--${prefix}-${kebab(k)}`, fmt(v as never)]);
  };

  add("color", t.colors, (v: string) => v);
  add("font", t.fonts, (v: string) => v);
  add("font-weight", t.fontWeights, (v: number) => String(v));
  for (const [k, v] of Object.entries(t.fontSizes)) out.push([`--text-${kebab(k)}`, size(v)]);
  add("leading", t.lineHeights, (v: number) => String(v));
  add("tracking", t.letterSpacings, (v: string) => v);
  out.push(["--space-unit", px(t.spaceUnit)]);
  for (const step of t.spaceSteps) out.push([spaceVar(step), px(step * t.spaceUnit)]);
  for (const [k, v] of Object.entries(t.fluidSpace)) out.push([`--space-${kebab(k)}`, clamp(v)]);
  add("radius", t.radii, px);
  add("shadow", t.shadows, (v: string) => v);
  add("blur", t.blurs, px);
  add("opacity", t.opacities, (v: number) => String(v));
  add("layout", t.layout, px);
  add("measure", t.measures, px);
  add("breakpoint", t.breakpoints, px);
  add("focus", t.focusRing, px);
  return out;
}

const HEADER = (source: string) =>
  `GENERATED by scripts/build-tokens.ts from src/styles/tokens/tokens.ts. Do not edit. ${source}`;

const scssMap = (name: string, entries: [key: string, value: string][]) =>
  `$${name}: (\n${entries.map(([k, v]) => `  ${k}: ${v},`).join("\n")}\n);`;

const quote = (s: string) => `"${s}"`;
const varRefs = (prefix: string, rec: Record<string, unknown>): [string, string][] =>
  Object.keys(rec).map((k) => [quote(kebab(k)), `var(--${prefix}-${kebab(k)})`]);

export function renderScss(t: Tokens): string {
  const vars = cssVariables(t)
    .map(([n, v]) => `  ${n}: ${v};`)
    .join("\n");

  return [
    `// ${HEADER("Run `npm run tokens`.")}`,
    "",
    "// Emitted once, by src/styles/globals.scss. Modules only read the maps below.",
    "@mixin css-variables {",
    "  :root {",
    vars.replace(/^/gm, "  "),
    "  }",
    "}",
    "",
    "// Maps for mixins and functions in src/styles/abstracts. Values are var() references,",
    "// except breakpoints, which are raw px because media queries cannot read custom properties.",
    scssMap(
      "breakpoints",
      Object.entries(t.breakpoints).map(([k, v]) => [quote(k), px(v)]),
    ),
    scssMap("colors", varRefs("color", t.colors)),
    scssMap("fonts", varRefs("font", t.fonts)),
    scssMap("font-weights", varRefs("font-weight", t.fontWeights)),
    scssMap("font-sizes", varRefs("text", t.fontSizes)),
    scssMap("line-heights", varRefs("leading", t.lineHeights)),
    scssMap("letter-spacings", varRefs("tracking", t.letterSpacings)),
    scssMap(
      "space",
      t.spaceSteps.map((s) => [String(s), `var(${spaceVar(s)})`]),
    ),
    scssMap("fluid-space", varRefs("space", t.fluidSpace)),
    scssMap("radii", varRefs("radius", t.radii)),
    scssMap("shadows", varRefs("shadow", t.shadows)),
    scssMap("measures", varRefs("measure", t.measures)),
    "",
  ].join("\n");
}

/** Tailwind v4 @theme: our tokens replace Tailwind's defaults so utilities only offer brand values. */
export function renderTailwindTheme(t: Tokens): string {
  const keep = ["--color-", "--font-", "--text-", "--leading-", "--tracking-", "--radius-", "--shadow-", "--blur-", "--breakpoint-"];
  const vars = cssVariables(t)
    .filter(([n]) => keep.some((p) => n.startsWith(p)))
    .map(([n, v]) => `  ${n}: ${v};`)
    .join("\n");

  return [
    `/* ${HEADER("Run `npm run tokens`.")} */`,
    "",
    "@theme {",
    "  --*: initial;",
    `  --spacing: ${px(t.spaceUnit)};`,
    vars,
    "}",
    "",
  ].join("\n");
}
